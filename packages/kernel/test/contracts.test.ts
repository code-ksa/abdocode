// oxlint-disable-next-line typescript-eslint/no-unnecessary-type-parameters
function identifier<T extends bigint>(value: number): T {
  // oxlint-disable-next-line typescript-eslint/no-unsafe-type-assertion
  return BigInt(value) as T
}

// oxlint-disable-next-line typescript-eslint/no-unnecessary-type-parameters
function opaque<T extends Uint8Array>(seed: number, length = 32): T {
  const bytes =
    seed === 0 ? new Uint8Array(length) : Uint8Array.from({ length }, (_, index) => (seed + index) % 255 || 1)
  // oxlint-disable-next-line typescript-eslint/no-unsafe-type-assertion
  return bytes as T
}

function asCommand(value: unknown): Command {
  // oxlint-disable-next-line typescript-eslint/no-unsafe-type-assertion
  return value as Command
}

function asAdmissionEvent(value: unknown): AdmissionEvent {
  // oxlint-disable-next-line typescript-eslint/no-unsafe-type-assertion
  return value as AdmissionEvent
}

function asTrustReceipt(value: unknown): UnverifiedTrustReceipt["receipt"] {
  // oxlint-disable-next-line typescript-eslint/no-unsafe-type-assertion
  return value as UnverifiedTrustReceipt["receipt"]
}

function replaceByte(source: Uint8Array, offset: number, value: number) {
  const changed = source.slice()
  changed[offset] = value
  return changed
}

function replaceU16(source: Uint8Array, offset: number, value: number) {
  const changed = source.slice()
  new DataView(changed.buffer, changed.byteOffset, changed.byteLength).setUint16(offset, value, true)
  return changed
}

function replaceU32(source: Uint8Array, offset: number, value: number) {
  const changed = source.slice()
  new DataView(changed.buffer, changed.byteOffset, changed.byteLength).setUint32(offset, value, true)
  return changed
}

function requireRecord(value: unknown, context: string): Record<string, unknown> {
  if (!isRecord(value)) throw new Error(`${context} must be an object`)
  return value
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value)
}

function requiredString(value: Record<string, unknown>, key: string) {
  const field = value[key]
  if (typeof field !== "string") throw new Error(`fixture ${key} must be a string`)
  return field
}

function hex(bytes: Uint8Array) {
  return [...bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("")
}

function normalizeCancelCommand(value: Command): Record<string, string> {
  if (value.tag !== "Cancel") throw new Error("shared fixture did not decode as Command.Cancel")
  return {
    tag: value.tag,
    command_id: value.value.command_id.toString(),
    cancellation_id: value.value.cancellation_id.toString(),
    proposal_id: value.value.proposal_id.toString(),
    scope: value.value.scope.tag,
    cause: value.value.cause.tag,
    requested_at_ms: value.value.requested_at_ms.toString(),
  }
}
