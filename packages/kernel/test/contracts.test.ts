  test("decoder fields bypass inherited setters and preserve the exact fixture", async () => {
    const fixture = new Uint8Array(await Bun.file(CANCEL_COMMAND_FIXTURE_PATH).arrayBuffer())
    const intrinsicDefineProperty = Object.defineProperty
    const inheritedKeys = ["command_id", "tag", "value"] as const
    const inheritedDescriptors = inheritedKeys.map((key) => Object.getOwnPropertyDescriptor(Object.prototype, key))
    let setterCalls = 0
    let roundTrip: Uint8Array | undefined
    let ownsDecodedFields = false
    let preservesOrdinaryPrototype = false
    let failure: unknown

    try {
      for (let index = 0; index < inheritedKeys.length; index += 1) {
        intrinsicDefineProperty(Object.prototype, inheritedKeys[index]!, {
          configurable: true,
          set: () => {
            setterCalls += 1
          },
        })
      }

      const decoded = decodeCommand(fixture)
      const payload = Object.getOwnPropertyDescriptor(decoded, "value")?.value as Record<string, unknown> | undefined
      ownsDecodedFields =
        Object.getOwnPropertyDescriptor(decoded, "tag")?.value === "Cancel" &&
        payload !== undefined &&
        Object.getOwnPropertyDescriptor(payload, "command_id") !== undefined
      preservesOrdinaryPrototype =
        payload !== undefined &&
        Object.getPrototypeOf(decoded) === Object.prototype &&
        Object.getPrototypeOf(payload) === Object.prototype
      roundTrip = encodeCommand(decoded)
    } catch (error) {
      failure = error
    } finally {
      for (let index = inheritedKeys.length - 1; index >= 0; index -= 1) {
        const key = inheritedKeys[index]!
        const descriptor = inheritedDescriptors[index]
        if (descriptor) intrinsicDefineProperty(Object.prototype, key, descriptor)
        else Reflect.deleteProperty(Object.prototype, key)
      }
    }

    expect(failure).toBeUndefined()
    expect(setterCalls).toBe(0)
    expect(ownsDecodedFields).toBeTrue()
    expect(preservesOrdinaryPrototype).toBeTrue()
    expect(roundTrip).toEqual(fixture)
  })

  test("public snapshots cannot mutate codec bytes, tags or nested descriptor rules", async () => {
    const fixture = new Uint8Array(await Bun.file(CANCEL_COMMAND_FIXTURE_PATH).arrayBuffer())
    const decoded = decodeCommand(fixture)
    const receipt = validTrustReceipt()
    const canonicalIntegrity = canonicalTrustReceiptIntegrityBytes(receipt.receipt)
    const originalMagic = MESSAGE_MAGIC.slice()
    const originalFingerprint = SCHEMA_FINGERPRINT.slice()
    const originalIntegrityDomain = TRUST_INTEGRITY_DOMAIN.slice()

    try {
      MESSAGE_MAGIC.fill(0)
      SCHEMA_FINGERPRINT.fill(0)
      TRUST_INTEGRITY_DOMAIN.fill(0)

      expect(Reflect.set(MESSAGE_TAGS, "Command", 99)).toBeFalse()
      expect(Reflect.set(CONTRACT_DESCRIPTOR, "version", 99)).toBeFalse()
      expect(Reflect.set(CONTRACT_DESCRIPTOR.magic, 0, 0)).toBeFalse()
      expect(Reflect.set(CONTRACT_DESCRIPTOR.schemaFingerprint, 0, 0)).toBeFalse()
      expect(Reflect.set(CONTRACT_DESCRIPTOR.trustIntegrityDomain, 0, 0)).toBeFalse()
      expect(Reflect.set(CONTRACT_DESCRIPTOR.messages, "Command", 99)).toBeFalse()

      const proposed = CONTRACT_DESCRIPTOR.types.ProposedIntent
      if (!proposed || proposed.kind !== "struct") throw new Error("ProposedIntent descriptor is not a struct")
      expect(Reflect.set(proposed.fields[0]!, "name", "forged_field")).toBeFalse()
      expect(Reflect.set(proposed.rules[0]!, "field", "forged_rule")).toBeFalse()

      const command = CONTRACT_DESCRIPTOR.types.Command
      if (!command || command.kind !== "union") throw new Error("Command descriptor is not a union")
      expect(Reflect.set(command.variants[0]!, "tag", 99)).toBeFalse()

      expect(decodeCommand(fixture)).toEqual(decoded)
      expect(encodeCommand(decoded)).toEqual(fixture)
      expect(canonicalTrustReceiptIntegrityBytes(receipt.receipt)).toEqual(canonicalIntegrity)
    } finally {
      MESSAGE_MAGIC.set(originalMagic)
      SCHEMA_FINGERPRINT.set(originalFingerprint)
      TRUST_INTEGRITY_DOMAIN.set(originalIntegrityDomain)
    }
  })

