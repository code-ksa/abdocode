/**
 * 🔴 **حارسُ التثبيت العالميّ كان يفوته الشكلُ الأكثرُ شيوعاً.**
 *
 * النمطُ القديم — `\b(?:npm|pnpm)\s+(?:install|add|i)\s+.*(?:\s-g\b|--global\b)` — يطلب
 * فراغاً **قبل** `-g` بعد أن استهلك الفراغَ الذي يلي `install`، فلا يطابق إلا العلمَ
 * المتأخّر. قِيس 2026-09-27 على اثنتي عشرة صيغة:
 *
 * | يمرّ (وهو المقصودُ منعُه) | يُرفض |
 * |---|---|
 * | `npm install -g typescript` · `npm i -g x` · `pnpm add -g eslint` | `npm install x -g` |
 * | `bun add -g x` · `bun install -g x` · `yarn global add x` | `npm install --global x` |
 *
 * فالحارسُ كان يمنع الصيغةَ التي لا يكتبها أحدٌ ويُمرّر التي يكتبها الجميع — وهو أسوأُ
 * من غيابه، لأنّه يُقرأ حمايةً. وكُشف باختبارٍ كُتب لسؤالٍ آخرَ: هل تسبق الحرّاسُ فرعَ
 * `run --bg`؟ سبقته فعلاً، ومرّ الأمرُ لأنّ الحارسَ نفسَه لا يمسكه.
 *
 * والقاعدةُ الآن مفصولةٌ إلى شرطَيها: **أمرُ تثبيت** و**علمٌ عالميّ في أيّ موضع**؛
 * ويُضاف `bun` و`yarn global` لأنّ العلّةَ واحدةٌ (تلويثُ الجهاز لا المشروع) والمانعُ
 * لا يُخصَّص بمديرِ حزمٍ بعينه.
 */

/** أمرُ تثبيتٍ لأيٍّ من مديري الحزم المشحونين. */
const INSTALL_COMMAND = /\b(?:npm|pnpm|bun)\s+(?:install|add|i)\b/iu

/** علمٌ عالميٌّ ككلمةٍ قائمةٍ بنفسها — لا داخل مسارٍ ولا داخل اسمِ حزمة. */
const GLOBAL_FLAG = /(?:^|\s)(?:-g|--global)(?=\s|$)/u

/** ‏`yarn` يجعل العالميّةَ كلمةً لا علماً. */
const YARN_GLOBAL = /\byarn\s+global\s+(?:add|upgrade)\b/iu

/**
 * هل يطلب هذا الأمرُ تثبيتاً عالميّاً؟
 *
 * فحصٌ نصّيٌّ على سطرِ الأمر — لا يُدّعى أنّه يفهم الصدفة: `npm run x -- -g` يُرفض
 * أيضاً، وهو رفضٌ مسمّى يكلّف صياغةً ثانية، بينما تمريرُ تثبيتٍ عالميٍّ يكلّف الجهاز.
 */
export const globalInstallRefused = (command: string): boolean =>
  YARN_GLOBAL.test(command) || (INSTALL_COMMAND.test(command) && GLOBAL_FLAG.test(command))
