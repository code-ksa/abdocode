/**
 * 🔴 **مهلةٌ ثابتةٌ لا تعرف طولَ ما طلبناه تقطع نداءً مشروعاً ثمّ تسمّيه انقطاعاً.**
 *
 * كانت المحاولاتُ الستُّ الأولى للمزوّد السحابيّ تُقطع عند 150 ثانيةً مهما كان
 * المطلوب. والقطعُ **قطعُنا نحن** — لكنّه يُصنَّف `transport failed before response`،
 * فيُعاد النداءُ بالسياق نفسِه فيُقطع ثانيةً، سبعَ مرّات، حتى يُحرق سقفُ الجولة.
 *
 * وقِيس: **خمسون «سقطةَ مزوّد» في مسحٍ كامل** كانت هذا، وليلتان قبله ظننّاهما شبكةً.
 * ولم يظهر السببُ حتى صار المِصنَفُ يحمله، فبان نصُّه: `tool timed out after 150000ms`.
 *
 * والزمنُ مقيسٌ على المزوّد **بلا تدفّق** (كما ينادي عاملُ Rust): 2000 توكنَ إخراجٍ
 * = 26ث · 4000 = 49ث · 8000 ≈ 100ث. فالكلفةُ تتبع **الإخراجَ المطلوب** لا السياق.
 *
 * والأرضيّةُ تبقى لتحفظ الغرضَ الأصليّ: تعليقٌ بلا بايتٍ يُكتشف مبكراً ولا يدفع
 * خمسَ دقائق (مقيس 09-14 على NIM).
 */

/** أرضيّةُ المحاولة المبكّرة — الغرضُ الأصليّ: كشفُ التعليق بلا بايت. */
export const CLOUD_EARLY_ATTEMPT_TIMEOUT_MS = 150_000

/** ما يكلّفه توكنُ إخراجٍ واحد — ضِعفا المقيس (12–13ms) هامشاً للنماذج الأبطأ. */
export const OUTPUT_MS_PER_TOKEN = 25

/**
 * ميزانيّةُ المحاولة المبكّرة: أرضيّةٌ ثابتة + سقفُ الإخراج المطلوب.
 *
 * `max_tokens` يُقرأ من الجسم المُرسَل نفسِه — فالمهلةُ تتبع **ما طُلب فعلاً**، ولا
 * تُنسَخ قيمةٌ تفترق عنه غداً. وغيابُ الحقل يُبقي الأرضيّةَ وحدها: **الغياب رفضٌ لا
 * إذن**، فلا يمنح طلبٌ بلا سقفٍ نفسَه مهلةً مفتوحة. والقصُّ النهائيُّ على سقف الطلب
 * يقع عند المُنادي، فلا يتجاوز هذا الرقمُ حدَّ عامل Rust المستورَد.
 */
export function earlyAttemptBudgetMs(body: string): number {
  const matched = /"max_tokens"\s*:\s*(\d{1,7})/u.exec(body)
  const maxOutput = matched === null ? 0 : Number(matched[1])
  return CLOUD_EARLY_ATTEMPT_TIMEOUT_MS + maxOutput * OUTPUT_MS_PER_TOKEN
}
