#!/usr/bin/env bun
/**
 * 🔴 **قشرةُ سطح المكتب تُبنى لويندوز، و`cargo check` على لينكس يفحص تركيباً لا نشحنه.**
 *
 * مقيس 2026-09-26 على CI (أوبونتو): سقط الفحصُ بأنّ `glib-2.0` غيرُ موجودة —
 * فتَوري على لينكس يطلب `webkit2gtk`/`gtk-3` ومكتباتِ النظام معها. والمنتَجُ
 * يشحن مُنصِّبَ NSIS لويندوز وحده (‏`windows-schema.json`، عاملُ العزل، PowerShell)،
 * فتنصيبُ سلسلةِ GTK على المُشغِّل يفحص بناءً **لا وجودَ له في المنتَج**.
 *
 * فيُتخطّى بالسبب منطوقاً — ويبقى الفحصُ كاملاً على ويندوز، حيث كسرُ الصندوق كسرٌ
 * حقيقيّ. وتخطٍّ صامتٌ كان سيعني أنّ أحداً سيقرأ «typecheck أخضر» فيظنّ الصندوقَ
 * مفحوصاً على كلّ مضيف.
 *
 * ⚠ ومتى استُهدفت لينكس فعلاً، هذا الملفُّ هو موضعُ القرار: يُنزع التخطّي وتُضاف
 * تبعيّاتُ النظام إلى المُشغِّل — لا يُصلَح بإسكاتِ الفحص.
 */
import { $ } from "bun"
import path from "node:path"

if (process.platform !== "win32") {
  console.error(
    `⏭ desktop typecheck: صندوقُ تَوري يُبنى لويندوز (مُنصِّب NSIS)، و${process.platform} يحتاج سلسلةَ GTK لبناءٍ لا نشحنه. تُخطّى بالسبب.`,
  )
  process.exit(0)
}

const manifest = path.join(path.resolve(import.meta.dir, ".."), "src-tauri", "Cargo.toml")
await $`cargo check --manifest-path ${manifest}`
